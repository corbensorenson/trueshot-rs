//! Unified Marching Cubes Implementation
//!
//! Surface extraction algorithm used across all reconstruction modes:
//! - 3DGS → Mesh (GS2Mesh)
//! - LiveHybrid meshification
//! - Photogrammetry mesh generation
//! - Scene reconstruction
//!
//! Implements the standard 256-case lookup table with trilinear interpolation.

use nalgebra as na;
use super::voxel::{VoxelGrid, VoxelData, TsdfVoxel, DensityVoxel};

/// Vertex output from marching cubes
#[derive(Clone, Debug, Default)]
pub struct MeshVertex {
    pub position: [f32; 3],
    pub normal: [f32; 3],
    pub uv: [f32; 2],
    pub color: [f32; 4],
}

/// Triangle output from marching cubes
#[derive(Clone, Debug)]
pub struct MeshTriangle {
    pub vertices: [MeshVertex; 3],
}

/// Complete mesh output
#[derive(Clone, Debug, Default)]
pub struct ExtractedMesh {
    pub vertices: Vec<MeshVertex>,
    pub indices: Vec<u32>,
    pub name: String,
}

impl ExtractedMesh {
    /// Get vertex count
    pub fn vertex_count(&self) -> usize {
        self.vertices.len()
    }
    
    /// Get triangle count
    pub fn triangle_count(&self) -> usize {
        self.indices.len() / 3
    }
}

/// Trait for extracting density from voxel data
pub trait DensitySource {
    fn density(&self) -> f32;
    fn color(&self) -> [f32; 3] { [1.0, 1.0, 1.0] }
}

impl DensitySource for f32 {
    fn density(&self) -> f32 { *self }
}

impl DensitySource for TsdfVoxel {
    fn density(&self) -> f32 { -self.tsdf } // Invert for surface at 0
    fn color(&self) -> [f32; 3] { self.color }
}

impl DensitySource for DensityVoxel {
    fn density(&self) -> f32 { self.density }
    fn color(&self) -> [f32; 3] { self.normalized_color() }
}

/// Marching cubes configuration
#[derive(Clone, Debug)]
pub struct MarchingCubesConfig {
    /// Surface threshold (isovalue)
    pub threshold: f32,
    /// Whether to compute normals
    pub compute_normals: bool,
    /// Whether to compute UVs
    pub compute_uvs: bool,
    /// UV scale
    pub uv_scale: f32,
}

impl Default for MarchingCubesConfig {
    fn default() -> Self {
        Self {
            threshold: 0.5,
            compute_normals: true,
            compute_uvs: true,
            uv_scale: 1.0,
        }
    }
}

/// CPU Marching Cubes implementation
pub struct MarchingCubes {
    config: MarchingCubesConfig,
}

impl MarchingCubes {
    pub fn new(config: MarchingCubesConfig) -> Self {
        Self { config }
    }
    
    /// Extract mesh from voxel grid
    pub fn extract<T: VoxelData + DensitySource>(&self, grid: &VoxelGrid<T>) -> ExtractedMesh {
        let mut vertices = Vec::new();
        let mut indices = Vec::new();
        
        // Process each cube (voxel cell)
        for z in 0..grid.dims[2].saturating_sub(1) {
            for y in 0..grid.dims[1].saturating_sub(1) {
                for x in 0..grid.dims[0].saturating_sub(1) {
                    self.process_cube(grid, [x, y, z], &mut vertices, &mut indices);
                }
            }
        }
        
        // Compute normals if requested
        if self.config.compute_normals && !vertices.is_empty() {
            self.compute_normals(&mut vertices, &indices);
        }
        
        ExtractedMesh {
            vertices,
            indices,
            name: String::from("marching_cubes_mesh"),
        }
    }
    
    /// Process a single cube
    fn process_cube<T: VoxelData + DensitySource>(
        &self,
        grid: &VoxelGrid<T>,
        origin: [usize; 3],
        vertices: &mut Vec<MeshVertex>,
        indices: &mut Vec<u32>,
    ) {
        // Get 8 corner values
        let corners = CORNER_OFFSETS.map(|offset| {
            let pos = [
                origin[0] + offset[0],
                origin[1] + offset[1],
                origin[2] + offset[2],
            ];
            grid.get(pos)
        });
        
        // Calculate cube index (which corners are above threshold)
        let mut cube_index = 0u8;
        for (i, corner) in corners.iter().enumerate() {
            if corner.density() > self.config.threshold {
                cube_index |= 1 << i;
            }
        }
        
        // Skip empty or full cubes
        if cube_index == 0 || cube_index == 255 {
            return;
        }
        
        // Get edge intersections
        let edge_mask = EDGE_TABLE[cube_index as usize];
        let mut edge_vertices = [[0.0f32; 3]; 12];
        let mut edge_colors = [[1.0f32; 3]; 12];
        
        for edge in 0..12 {
            if edge_mask & (1 << edge) != 0 {
                let [v0, v1] = EDGE_CONNECTIONS[edge];
                let d0 = corners[v0].density();
                let d1 = corners[v1].density();
                
                // Interpolate along edge
                let t = if (d1 - d0).abs() > 1e-6 {
                    (self.config.threshold - d0) / (d1 - d0)
                } else {
                    0.5
                };
                
                let p0 = CORNER_OFFSETS[v0];
                let p1 = CORNER_OFFSETS[v1];
                
                edge_vertices[edge] = [
                    (origin[0] as f32 + p0[0] as f32 + (p1[0] as f32 - p0[0] as f32) * t) * grid.voxel_size + grid.origin.x,
                    (origin[1] as f32 + p0[1] as f32 + (p1[1] as f32 - p0[1] as f32) * t) * grid.voxel_size + grid.origin.y,
                    (origin[2] as f32 + p0[2] as f32 + (p1[2] as f32 - p0[2] as f32) * t) * grid.voxel_size + grid.origin.z,
                ];
                
                // Interpolate color
                let c0 = corners[v0].color();
                let c1 = corners[v1].color();
                edge_colors[edge] = [
                    c0[0] + (c1[0] - c0[0]) * t,
                    c0[1] + (c1[1] - c0[1]) * t,
                    c0[2] + (c1[2] - c0[2]) * t,
                ];
            }
        }
        
        // Generate triangles
        let tri_table = &TRI_TABLE[cube_index as usize];
        let mut i = 0;
        while tri_table[i] != -1 {
            let base_idx = vertices.len() as u32;
            
            for j in 0..3 {
                let edge = tri_table[i + j] as usize;
                let pos = edge_vertices[edge];
                let color = edge_colors[edge];
                
                let uv = if self.config.compute_uvs {
                    [pos[0] * self.config.uv_scale, pos[1] * self.config.uv_scale]
                } else {
                    [0.0, 0.0]
                };
                
                vertices.push(MeshVertex {
                    position: pos,
                    normal: [0.0, 0.0, 0.0], // Computed later
                    uv,
                    color: [color[0], color[1], color[2], 1.0],
                });
            }
            
            indices.push(base_idx);
            indices.push(base_idx + 1);
            indices.push(base_idx + 2);
            
            i += 3;
        }
    }
    
    /// Compute normals from triangles
    fn compute_normals(&self, vertices: &mut [MeshVertex], indices: &[u32]) {
        // Compute face normals and accumulate to vertices
        for tri in indices.chunks(3) {
            if tri.len() < 3 { continue; }
            
            let v0 = &vertices[tri[0] as usize];
            let v1 = &vertices[tri[1] as usize];
            let v2 = &vertices[tri[2] as usize];
            
            let p0 = na::Vector3::new(v0.position[0], v0.position[1], v0.position[2]);
            let p1 = na::Vector3::new(v1.position[0], v1.position[1], v1.position[2]);
            let p2 = na::Vector3::new(v2.position[0], v2.position[1], v2.position[2]);
            
            let normal = (p1 - p0).cross(&(p2 - p0));
            
            for &idx in tri {
                let v = &mut vertices[idx as usize];
                v.normal[0] += normal.x;
                v.normal[1] += normal.y;
                v.normal[2] += normal.z;
            }
        }
        
        // Normalize
        for v in vertices.iter_mut() {
            let len = (v.normal[0].powi(2) + v.normal[1].powi(2) + v.normal[2].powi(2)).sqrt();
            if len > 1e-6 {
                v.normal[0] /= len;
                v.normal[1] /= len;
                v.normal[2] /= len;
            }
        }
    }
}

